// regTestImporter resolves imports from the packages type-checked so far.
type regTestImporter struct {
	pkgs map[string]*types.Package
}

func (i regTestImporter) Import(path string) (*types.Package, error) {
	if p, ok := i.pkgs[path]; ok {
		return p, nil
	}
	return nil, fmt.Errorf("package %q is not part of the test program", path)
}

// loadRegTestPackages type-checks the given sources in order. Each entry is a package path and
// its single source file.
func loadRegTestPackages(t *testing.T, sources [][2]string) []*packages.Package {
	t.Helper()
	fset := token.NewFileSet()
	imp := regTestImporter{pkgs: make(map[string]*types.Package)}
	var out []*packages.Package
	for _, src := range sources {
		path, code := src[0], src[1]
		file, err := parser.ParseFile(fset, strings.ReplaceAll(path, "/", "_")+".go", code, parser.ParseComments)
		require.NoError(t, err)
		info := &types.Info{
			Types:      make(map[ast.Expr]types.TypeAndValue),
			Defs:       make(map[*ast.Ident]types.Object),
			Uses:       make(map[*ast.Ident]types.Object),
			Selections: make(map[*ast.SelectorExpr]*types.Selection),
			Implicits:  make(map[ast.Node]types.Object),
		}
		pkg, err := (&types.Config{Importer: imp}).Check(path, fset, []*ast.File{file}, info)
		require.NoError(t, err, path)
		imp.pkgs[path] = pkg
		out = append(out, &packages.Package{PkgPath: path, Fset: fset, Syntax: []*ast.File{file}, Types: pkg, TypesInfo: info})
	}
	return out
}

const _regTestGRPC = `package grpc

type ServiceRegistrar interface{ RegisterService(desc, impl any) }

type Server struct{}

func (*Server) RegisterService(desc, impl any) {}
`

const _regTestPB = `// Code generated by protoc-gen-go-grpc. DO NOT EDIT.

package pb

import "google.golang.org/grpc"

type KVServer interface {
	Get() error
	Put() error
}

type UnimplementedKVServer struct{}

func (UnimplementedKVServer) Get() error { return nil }
func (UnimplementedKVServer) Put() error { return nil }

func RegisterKVServer(s grpc.ServiceRegistrar, srv KVServer) { s.RegisterService(nil, srv) }

type LeaseServer interface{ Grant() error }

func RegisterLeaseServer(s grpc.ServiceRegistrar, srv LeaseServer) { s.RegisterService(nil, srv) }

type AuthServer interface{ Login() error }

func RegisterAuthServer(s *grpc.Server, srv AuthServer) { s.RegisterService(nil, srv) }

type WatchServer interface{ Watch() error }

func RegisterWatchServer(s grpc.ServiceRegistrar, srv WatchServer) { s.RegisterService(nil, srv) }

// NewFxWatchProcedures is an fx-style registrar: the handler arrives by type.
func NewFxWatchProcedures() any {
	return func(p struct{ Server WatchServer }) { RegisterWatchServer(nil, p.Server) }
}
`

const _regTestApp = `package app

import (
	"example.com/pb"
	"google.golang.org/grpc"
)

// kv is registered through a wrapper that shadows Put and promotes Get.
type kv struct{}

func (*kv) Get() error { return nil }
func (*kv) Put() error { return nil }
func (*kv) Close()     {}

func newKV() pb.KVServer { return &kv{} }

type quotaKV struct{ pb.KVServer }

func (*quotaKV) Put() error { return nil }

func newQuotaKV() pb.KVServer { return &quotaKV{newKV()} }

// unregisteredKV implements the interface but never reaches a registration.
type unregisteredKV struct{ pb.UnimplementedKVServer }

func (unregisteredKV) Get() error { return nil }

// lease is registered through a local variable assigned from a two-result constructor.
type lease struct{}

func (lease) Grant() error { return nil }

func newLease() (pb.LeaseServer, error) { return lease{}, nil }

// otherLease flows into the same interface elsewhere, but is not what gets registered.
type otherLease struct{}

func (otherLease) Grant() error { return nil }

var spare pb.LeaseServer = otherLease{}

// auth is registered directly; Login is promoted from an embedded struct.
type authBase struct{}

func (authBase) Login() error { return nil }

type auth struct{ authBase }

// watch is provided by type and registered through the fx-style registrar.
type watch struct{}

func (*watch) Watch() error { return nil }

func newWatch() pb.WatchServer { return &watch{} }

func provide(constructors ...any) {}

func Run(s *grpc.Server) {
	pb.RegisterKVServer(s, newQuotaKV())
	l, _ := newLease()
	pb.RegisterLeaseServer(s, l)
	pb.RegisterAuthServer(s, auth{})
	provide(newWatch, pb.NewFxWatchProcedures())
}
`

func registeredHandlerNames(pkgs []*packages.Package, inCodebase func(string) bool) []string {
	var names []string
	for _, h := range newRegistrationIndex(pkgs).registeredHandlers(pkgs, inCodebase) {
		names = append(names, h.fn.FullName())
	}
	sort.Strings(names)
	return names
}

func TestRegisteredHandlers(t *testing.T) {
	t.Parallel()

	pkgs := loadRegTestPackages(t, [][2]string{
		{"google.golang.org/grpc", _regTestGRPC},
		{"example.com/pb", _regTestPB},
		{"example.com/app", _regTestApp},
	})

	require.Equal(t, []string{
		"(*example.com/app.kv).Get",      // promoted through quotaKV's embedded interface
		"(*example.com/app.quotaKV).Put", // shadows kv.Put, which is not a handler
		"(*example.com/app.watch).Watch", // fx-style registrar: handler provided by type
		"(example.com/app.authBase).Login",
		"(example.com/app.lease).Grant", // local variable resolved through its constructor
	}, registeredHandlerNames(pkgs, func(string) bool { return true }))

	require.Empty(t, registeredHandlerNames(pkgs, func(string) bool { return false }), "out-of-codebase registrations and handlers are dropped")
}

