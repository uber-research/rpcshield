func TestIsGeneratedFile(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		src       string
		generated bool
	}{
		{"go convention", "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n\npackage p\n", true},
		{"marker split over lines", "// Code generated by thrift-to-protobuf-objectmapper-go\n// DO NOT EDIT!\n\npackage p\n", true},
		{"thriftrw and yarpc", "// Code generated by thriftrw-plugin-yarpc\n// @generated\n\npackage p\n", true},
		{"@generated alone", "// @generated\n\npackage p\n", true},
		{"marker after the package clause", "package p\n\n// Code generated by hand. DO NOT EDIT.\nvar x int\n", false},
		{"mention inside a sentence", "// This file is not Code generated by anything.\n\npackage p\n", false},
		{"no comment", "package p\n", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file, err := parser.ParseFile(token.NewFileSet(), "p.go", tt.src, parser.ParseComments)
			require.NoError(t, err)
			require.Equal(t, tt.generated, isGeneratedFile(file))
		})
	}
}

func TestTypeKey_LocalTypesAreDistinct(t *testing.T) {
	t.Parallel()

	pkgs := loadRegTestPackages(t, [][2]string{
		{"example.com/local", `package local

func A() any { type T struct{}; return T{} }
func B() any { type T struct{}; return T{} }

type T struct{}
`},
	})
	var keys []string
	info := pkgs[0].TypesInfo
	for id, obj := range info.Defs {
		if tn, ok := obj.(*types.TypeName); ok && id.Name == "T" {
			keys = append(keys, typeKey(tn.Type()))
		}
	}
	sort.Strings(keys)
	require.Len(t, keys, 3)
	require.Equal(t, "example.com/local.T", keys[0], "the package-level type keeps its plain name")
	require.NotEqual(t, keys[1], keys[2], "function-local types with the same name get distinct keys")
}
